import { collectKeys, durationToSeconds, firstOf, num, plateObjects, thumbnails } from "./common";
import type { GcodeChunks, GcodeParser, ParsedGcode } from "./types";

/**
 * Creality Print 7.x plain .gcode (an OrcaSlicer fork). Facts from Joe's files (D40):
 * - first lines: `;TIME:<s>`, `;Filament used:<m>m`, `;Layer height:` and a HEADER_BLOCK;
 * - totals (`; filament used [g] = …`) and the CONFIG_BLOCK are at the END of the file;
 * - objects appear as `; printing object <name> id:<n> copy <n>` throughout the moves;
 * - thumbnails: `; png begin W*H …` base64 lines `; png end`.
 * OrcaSlicer and Bambu Studio write the same layout, so one parse serves the whole family;
 * each keeps its own parser id so a recipe records which slicer made it.
 */
function orcaFamilyParser(id: string, generatedBy: RegExp, tailHint?: RegExp): GcodeParser {
  return {
    id,
    version: "1",
    detect(head, tail) {
      if (generatedBy.test(head)) return true;
      // Fallback when the header line is missing: an Orca-style config block, never a PrusaSlicer one.
      return !!tailHint && tailHint.test(tail) && /; CONFIG_BLOCK_START/.test(tail);
    },
    parse: parseOrcaFamily,
  };
}

function parseOrcaFamily(this: GcodeParser, { head, tail, objectLines }: GcodeChunks): ParsedGcode {
  const raw: Record<string, string> = {};
  // Header block and the top lines
  const headerBlock = head.match(/; HEADER_BLOCK_START([\s\S]*?); HEADER_BLOCK_END/)?.[1] ?? "";
  collectKeys(headerBlock, raw);
  const config = tail.match(/; CONFIG_BLOCK_START([\s\S]*?); CONFIG_BLOCK_END/)?.[1] ?? "";
  collectKeys(config, raw);
  // Totals sit just before CONFIG_BLOCK_START
  const beforeConfig = tail.split("; CONFIG_BLOCK_START")[0]!.split(/\r?\n/).slice(-40).join("\n");
  collectKeys(beforeConfig, raw);

  const top = head.slice(0, 2000);
  const timeTop = num(top.match(/^;TIME:([\d.]+)/m)?.[1]);
  const metresTop = num(top.match(/^;Filament used:([\d.]+)m/m)?.[1]);
  const generated = head.match(/; generated by (\S+?)\s+V?([\d.]+)/);

  const totalMm = num(raw["filament used [mm]"]) ?? (metresTop != null ? metresTop * 1000 : null);
  const supportsEnabled = raw["enable_support"] == null ? null : raw["enable_support"] === "1";

  return {
    parser: this.id,
    parserVersion: this.version,
    slicerName: generated?.[1] ?? null,
    slicerVersion: generated?.[2] ?? null,
    printerModel: raw["printer_model"] ?? null,
    nozzleMm: num(firstOf(raw["nozzle_diameter"])),
    material: firstOf(raw["filament_type"]) ?? null,
    colour: firstOf(raw["filament_colour"]) ?? null,
    layerHeightMm: num(raw["layer_height"]) ?? num(top.match(/^;Layer height:([\d.]+)/m)?.[1]),
    totalLayers: num(raw["total layer number"]),
    totalGrams:
      num(raw["total filament used [g]"]) ?? num(raw["filament used [g]"]) ?? num(raw["total filament weight [g]"]),
    totalMm,
    totalCm3: num(raw["filament used [cm3]"]),
    estimatedSeconds: timeTop ?? durationToSeconds(raw["estimated printing time (normal mode)"]),
    nozzleTempC: num(firstOf(raw["nozzle_temperature"])),
    bedTempC: num(firstOf(raw["hot_plate_temp"])),
    bedType: raw["curr_bed_type"] ?? null,
    infillPct: num(raw["sparse_infill_density"]),
    infillPattern: raw["sparse_infill_pattern"] ?? null,
    wallLoops: num(raw["wall_loops"]),
    supportType: supportsEnabled === false ? "none" : (raw["support_type"] ?? null),
    supportsEnabled,
    slicerFilamentCost: num(firstOf(raw["filament_cost"])),
    objects: plateObjects(objectLines),
    thumbnails: thumbnails(head),
    rawHeader: raw,
  };
}

export const crealityPrintParser = orcaFamilyParser(
  "creality_print_gcode",
  /; generated by Creality_Print/i,
  /; printer_settings_id = Creality/i,
);
export const orcaSlicerParser = orcaFamilyParser("orca_slicer_gcode", /; generated by OrcaSlicer/i);
export const bambuStudioParser = orcaFamilyParser("bambu_studio_gcode", /; generated by BambuStudio/i);
