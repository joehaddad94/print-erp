import type { GcodeChunks, GcodeParser, ParsedGcode, PlateObject, Thumbnail } from "./types";

/**
 * Creality Print 7.x plain .gcode (an OrcaSlicer fork). Facts from Joe's files (D40):
 * - first lines: `;TIME:<s>`, `;Filament used:<m>m`, `;Layer height:` and a HEADER_BLOCK;
 * - totals (`; filament used [g] = …`) and the CONFIG_BLOCK are at the END of the file;
 * - objects appear as `; printing object <name> id:<n> copy <n>` throughout the moves;
 * - thumbnails: `; png begin W*H …` base64 lines `; png end`.
 */

const num = (v: string | undefined): number | null => {
  if (v == null) return null;
  const n = Number.parseFloat(v.replace(/[%\s]/g, ""));
  return Number.isFinite(n) ? n : null;
};

const firstOf = (v: string | undefined): string | undefined => v?.split(/[;,]/)[0]?.trim();

/** "1h 47m 30s" / "2d 3h 4m 5s" / "45m 2s" → seconds. */
export function durationToSeconds(text: string | undefined): number | null {
  if (!text) return null;
  let total = 0;
  let matched = false;
  for (const [, n, unit] of text.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    matched = true;
    total += Number(n) * { d: 86400, h: 3600, m: 60, s: 1 }[unit as "d" | "h" | "m" | "s"];
  }
  return matched ? total : null;
}

/** Collects `; key = value` and `; key: value` comment lines. Later values do not overwrite earlier ones. */
function collectKeys(text: string, into: Record<string, string>) {
  for (const line of text.split(/\r?\n/)) {
    if (!line.startsWith(";")) continue;
    const body = line.replace(/^;\s?/, "");
    const m = body.match(/^([A-Za-z_][\w \[\]().-]*?)\s*(?:=|:)\s*(.*)$/);
    if (!m) continue;
    const key = m[1]!.trim();
    if (key.length > 80 || /^(png|plate_)/.test(key)) continue;
    if (!(key in into)) into[key] = m[2]!.trim().replace(/^"(.*)"$/, "$1");
  }
}

function thumbnails(head: string): Thumbnail[] {
  const out: Thumbnail[] = [];
  const re = /^; png begin (\d+)[*x](\d+)[^\n]*\n([\s\S]*?)^; png end/gm;
  for (const m of head.matchAll(re)) {
    const base64Png = m[3]!
      .split(/\r?\n/)
      .map((l) => l.replace(/^;\s?/, "").trim())
      .join("");
    if (base64Png) out.push({ width: Number(m[1]), height: Number(m[2]), base64Png });
  }
  return out.sort((a, b) => b.width * b.height - a.width * a.height);
}

const HASH_NAME = /^(?:.*\/)?[0-9a-f]{16,}\.(?:stl|3mf|obj|step)$/i;

export function plateObjects(objectLines: string[]): PlateObject[] {
  const ids = new Map<string, Set<string>>();
  for (const line of objectLines) {
    const m = line.match(/^; printing object (.+?) id:(\S+) copy (\d+)/);
    if (!m) continue;
    let name = m[1]!;
    try {
      name = decodeURIComponent(name);
    } catch {
      /* keep raw */
    }
    const key = `${m[2]}:${m[3]}`;
    if (!ids.has(name)) ids.set(name, new Set());
    ids.get(name)!.add(key);
  }
  let unnamed = 0;
  return [...ids.entries()].map(([rawName, set]) => {
    const base = rawName.split("/").pop()!;
    const displayName = HASH_NAME.test(rawName) ? `Object ${++unnamed}` : base.replace(/\.(stl|3mf|obj|step)$/i, "");
    return { rawName, displayName, count: set.size };
  });
}

export const crealityPrintParser: GcodeParser = {
  id: "creality_print_gcode",
  version: "1",

  detect(head, tail) {
    return /generated by Creality_Print/i.test(head) || /; printer_settings_id = Creality/i.test(tail);
  },

  parse({ head, tail, objectLines }: GcodeChunks): ParsedGcode {
    const raw: Record<string, string> = {};
    // Header block and the top lines
    const headerBlock = head.match(/; HEADER_BLOCK_START([\s\S]*?); HEADER_BLOCK_END/)?.[1] ?? "";
    collectKeys(headerBlock, raw);
    const config = tail.match(/; CONFIG_BLOCK_START([\s\S]*?); CONFIG_BLOCK_END/)?.[1] ?? "";
    collectKeys(config, raw);
    // Totals sit just before CONFIG_BLOCK_START
    const beforeConfig = tail.split("; CONFIG_BLOCK_START")[0]!.split(/\r?\n/).slice(-40).join("\n");
    collectKeys(beforeConfig, raw);

    const top = head.slice(0, 2000);
    const timeTop = num(top.match(/^;TIME:([\d.]+)/m)?.[1]);
    const metresTop = num(top.match(/^;Filament used:([\d.]+)m/m)?.[1]);
    const generated = head.match(/; generated by (\S+?)\s+V?([\d.]+)/);

    const totalMm = num(raw["filament used [mm]"]) ?? (metresTop != null ? metresTop * 1000 : null);
    const supportsEnabled = raw["enable_support"] == null ? null : raw["enable_support"] === "1";

    return {
      parser: this.id,
      parserVersion: this.version,
      slicerName: generated?.[1] ?? null,
      slicerVersion: generated?.[2] ?? null,
      printerModel: raw["printer_model"] ?? null,
      nozzleMm: num(firstOf(raw["nozzle_diameter"])),
      material: firstOf(raw["filament_type"]) ?? null,
      colour: firstOf(raw["filament_colour"]) ?? null,
      layerHeightMm: num(raw["layer_height"]) ?? num(top.match(/^;Layer height:([\d.]+)/m)?.[1]),
      totalLayers: num(raw["total layer number"]),
      totalGrams: num(raw["total filament used [g]"]) ?? num(raw["filament used [g]"]),
      totalMm,
      totalCm3: num(raw["filament used [cm3]"]),
      estimatedSeconds: timeTop ?? durationToSeconds(raw["estimated printing time (normal mode)"]),
      nozzleTempC: num(firstOf(raw["nozzle_temperature"])),
      bedTempC: num(firstOf(raw["hot_plate_temp"])),
      bedType: raw["curr_bed_type"] ?? null,
      infillPct: num(raw["sparse_infill_density"]),
      infillPattern: raw["sparse_infill_pattern"] ?? null,
      wallLoops: num(raw["wall_loops"]),
      supportType: supportsEnabled === false ? "none" : (raw["support_type"] ?? null),
      supportsEnabled,
      slicerFilamentCost: num(firstOf(raw["filament_cost"])),
      objects: plateObjects(objectLines),
      thumbnails: thumbnails(head),
      rawHeader: raw,
    };
  },
};
