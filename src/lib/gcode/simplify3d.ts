import { durationToSeconds, firstOf, num } from "./common";
import type { GcodeChunks, GcodeParser, ParsedGcode } from "./types";

/**
 * Simplify3D 4.x/5.x .gcode. Settings are `;   key,value` lines at the top; a "Build Summary"
 * at the end has `;   Build time: 1 hours 51 minutes`, `;   Filament length: 13788.5 mm (13.79 m)`,
 * `;   Plastic weight: 41.46 g (0.09 lb)`.
 */
export const simplify3dParser: GcodeParser = {
  id: "simplify3d_gcode",
  version: "1",

  detect(head) {
    return /^; G-Code generated by Simplify3D/im.test(head);
  },

  parse({ head, tail }: GcodeChunks): ParsedGcode {
    const raw: Record<string, string> = {};
    for (const [, k, v] of head.matchAll(/^;\s+([A-Za-z][A-Za-z0-9]*),(.*)$/gm)) {
      if (!(k! in raw)) raw[k!] = v!.trim();
    }
    for (const [, k, v] of tail.matchAll(
      /^;\s+(Build time|Filament length|Plastic volume|Plastic weight|Material cost):\s*(.*)$/gm,
    )) {
      raw[k!] = v!.trim();
    }
    const generated = head.match(/generated by Simplify3D\(R\) Version ([\d.]+)/i);
    const time = raw["Build time"]
      ?.replace(/hours?/g, "h")
      .replace(/minutes?/g, "m")
      .replace(/seconds?/g, "s");
    const support = raw["generateSupport"];

    return {
      parser: this.id,
      parserVersion: this.version,
      slicerName: "Simplify3D",
      slicerVersion: generated?.[1] ?? null,
      printerModel: raw["machineTypeOverride"] ?? null,
      nozzleMm: num(firstOf(raw["extruderDiameter"])),
      material: null,
      colour: null,
      layerHeightMm: num(raw["layerHeight"]),
      totalLayers: null,
      totalGrams: num(raw["Plastic weight"]?.match(/^([\d.]+)\s*g/)?.[1]),
      totalMm: num(raw["Filament length"]?.match(/^([\d.]+)\s*mm/)?.[1]),
      totalCm3:
        num(raw["Plastic volume"]?.match(/^([\d.]+)\s*mm/)?.[1]) != null
          ? Number((num(raw["Plastic volume"]!.match(/^([\d.]+)/)![1])! / 1000).toFixed(2))
          : null,
      estimatedSeconds: durationToSeconds(time),
      nozzleTempC: num(firstOf(raw["temperatureSetpointTemperatures"])),
      bedTempC: null,
      bedType: null,
      infillPct: num(raw["infillPercentage"]),
      infillPattern: raw["internalInfillPattern"] ?? null,
      wallLoops: num(raw["perimeterOutlines"]),
      supportType: support === "0" ? "none" : null,
      supportsEnabled: support == null ? null : support === "1",
      slicerFilamentCost: null,
      objects: [],
      thumbnails: [],
      rawHeader: raw,
      estimated: {},
    };
  },
};
